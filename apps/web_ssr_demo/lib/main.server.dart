/// Server entrypoint — a Dart HTTP server that renders every page to HTML.
/// Runs on your machine with `jaspr serve` (http://localhost:8080).
library;

import 'dart:io';

import 'package:jaspr/dom.dart';
import 'package:jaspr/server.dart';
import 'package:shelf/shelf.dart';
import 'package:shelf/shelf_io.dart' as shelf_io;
import 'package:shelf_router/shelf_router.dart';

import 'app.dart';
import 'config.dart';
import 'di/server_injection.dart';
import 'main.server.options.dart'; // generated by jaspr_builder
import 'seo/crawler_files.dart';

void main() async {
  Jaspr.initializeApp(options: defaultServerOptions);
  if (!_initialized) {
    ServerInjection.init(baseUrl: apiBaseUrl);
    _initialized = true;
  }

  final router = Router()
    // Crawler files: real text/XML responses, not HTML pages.
    ..get('/robots.txt', CrawlerFiles.robots)
    ..get('/sitemap.xml', CrawlerFiles.sitemap)
    // Everything else: pages rendered by Jaspr.
    ..mount(
      '/',
      serveApp(
        (request, render) => render(
          Document(
            lang: 'en',
            title: 'Pokédex',
            head: [link(rel: 'icon', href: '/favicon.ico')],
            body: const App(),
          ),
        ),
      ),
    );

  // Hot-reload safe server setup (same pattern as Jaspr's shelf template).
  final reloadLock = activeReloadLock = Object();
  final port = int.tryParse(Platform.environment['PORT'] ?? '') ?? 8080;
  final server = await shelf_io.serve(
    const Pipeline().addHandler(router.call),
    InternetAddress.anyIPv4,
    port,
    shared: true,
  );
  if (reloadLock != activeReloadLock) {
    await server.close();
    return;
  }
  await activeServer?.close();
  activeServer = server;
  print('Serving at http://${server.address.host}:${server.port}');
}

/// GetIt registrations must survive hot reloads (main() runs again).
bool _initialized = false;
HttpServer? activeServer;
Object? activeReloadLock;
